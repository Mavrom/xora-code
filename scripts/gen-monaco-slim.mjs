// Generates src/features/editor/monaco/slim.js: Monaco's editor.main without the
// TypeScript language service (≈7 MB worker) and the LSP client. Re-run after a
// monaco-editor upgrade: `node scripts/gen-monaco-slim.mjs`.
import { readFileSync, writeFileSync } from "node:fs";

const main = readFileSync("node_modules/monaco-editor/esm/vs/editor/editor.main.js", "utf8");
const DROP = [
  /monaco-lsp-client/,
  /\{ index as lsp \}/,
  /features\/typescript\/register/,
  /as typescript \}/,
];

const toAlias = (spec) => {
  // Specifiers are relative to esm/vs/editor/.
  if (spec.startsWith("./")) return `monaco-esm/editor/${spec.slice(2)}`;
  if (spec.startsWith("../")) return `monaco-esm/${spec.slice(3)}`;
  return spec;
};

const lines = main
  .split("\n")
  .filter((line) => line.trim() && !DROP.some((re) => re.test(line)))
  .map((line) =>
    line.replace(/(['"])(\.{1,2}\/[^'"]+)\1/, (_, q, spec) => `${q}${toAlias(spec)}${q}`),
  );

writeFileSync(
  "src/features/editor/monaco/slim.js",
  `// GENERATED by scripts/gen-monaco-slim.mjs from monaco-editor's editor.main.js.\n` +
    `// Same editor and languages, minus the TypeScript language service and LSP client.\n` +
    lines.join("\n") +
    "\n",
);
console.log(`slim.js: ${lines.length} lines`);
